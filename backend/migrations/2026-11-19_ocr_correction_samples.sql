-- WHAT A SAMPLE IS, AND WHY IT COSTS NOBODY ANY WORK
-- ---------------------------------------------------
-- Every time a teacher clicks an answer on a Test Paper and corrects what the
-- scanner read, they produce a labelled pair: the reader saw X, a human says
-- it was Y. That is a training example, generated by ordinary marking. No
-- collection exercise, no labelling session, nobody asked to do anything
-- extra.
--
-- Until now it was thrown away. `paper_answer_service.override_answer`
-- computes `old_answer`, uses it for the confirmation message, and overwrites
-- `paper_scores.student_answer` — so the evidence is destroyed at the exact
-- moment it is created. This table keeps it.
--
-- WHAT IS NOT STORED, ON PURPOSE
-- -------------------------------
-- No student name, no student number, no answer-key content. A sample is a
-- fact about the READER: a glyph it produced and the glyph a human says was
-- on the page. `score_id` and `exam_id` are kept for traceability and both
-- go to NULL rather than CASCADE if the paper or exam is deleted — the
-- dataset is about the recogniser and outlives any one paper.
--
-- `confidence` is the ocr_confidence the reader reported FOR THE READING IT
-- GOT WRONG. That column answers the question behind Alex's point 5 better
-- than anything else here: was the recogniser confident when it was wrong?
--
-- Run with the backend STOPPED:
--   docker exec -i learnlens_db sh -c 'psql -U "$POSTGRES_USER" -d "$POSTGRES_DB"' \
--       < backend/migrations/2026-11-19_ocr_correction_samples.sql
--
-- Safe to run twice: every statement is guarded.

BEGIN;

CREATE TABLE IF NOT EXISTS public.ocr_correction_samples (
    sample_id       integer                  NOT NULL,
    score_id        integer,
    exam_id         integer,
    question_number smallint,
    seen            character varying(100)   NOT NULL,
    means           character varying(100)   NOT NULL,
    confidence      numeric(5, 2),
    corrected_by    integer,
    created_at      timestamp with time zone DEFAULT now() NOT NULL
);

CREATE SEQUENCE IF NOT EXISTS public.ocr_correction_samples_sample_id_seq
    AS integer START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
ALTER SEQUENCE public.ocr_correction_samples_sample_id_seq
    OWNED BY public.ocr_correction_samples.sample_id;
ALTER TABLE ONLY public.ocr_correction_samples
    ALTER COLUMN sample_id SET DEFAULT nextval('public.ocr_correction_samples_sample_id_seq'::regclass);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ocr_correction_samples_pkey') THEN
        ALTER TABLE ONLY public.ocr_correction_samples
            ADD CONSTRAINT ocr_correction_samples_pkey PRIMARY KEY (sample_id);
    END IF;

    -- SET NULL, never CASCADE. Deleting a paper must not delete the record of
    -- what the reader got wrong on it: the sample is about the recogniser.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ocr_correction_samples_score_id_fkey') THEN
        ALTER TABLE ONLY public.ocr_correction_samples
            ADD CONSTRAINT ocr_correction_samples_score_id_fkey FOREIGN KEY (score_id)
            REFERENCES public.paper_scores(score_id) ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ocr_correction_samples_exam_id_fkey') THEN
        ALTER TABLE ONLY public.ocr_correction_samples
            ADD CONSTRAINT ocr_correction_samples_exam_id_fkey FOREIGN KEY (exam_id)
            REFERENCES public.exams(exam_id) ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ocr_correction_samples_corrected_by_fkey') THEN
        ALTER TABLE ONLY public.ocr_correction_samples
            ADD CONSTRAINT ocr_correction_samples_corrected_by_fkey FOREIGN KEY (corrected_by)
            REFERENCES public.users(user_id) ON DELETE SET NULL;
    END IF;

    -- The same refusals the correction pass makes, enforced where they cannot
    -- be bypassed. A blank is not a misreading, and a contested reading is not
    -- a reading of one mark.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_ocr_correction_samples_nonblank') THEN
        ALTER TABLE ONLY public.ocr_correction_samples
            ADD CONSTRAINT ck_ocr_correction_samples_nonblank
            CHECK (btrim(seen) <> '' AND btrim(means) <> ''
                   AND btrim(seen) <> U&'\2014' AND btrim(means) <> U&'\2014');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_ocr_correction_samples_not_contested') THEN
        ALTER TABLE ONLY public.ocr_correction_samples
            ADD CONSTRAINT ck_ocr_correction_samples_not_contested
            CHECK (position('|' in seen) = 0 AND position('|' in means) = 0);
    END IF;
    -- A sample where nothing changed is not evidence of anything.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_ocr_correction_samples_moved') THEN
        ALTER TABLE ONLY public.ocr_correction_samples
            ADD CONSTRAINT ck_ocr_correction_samples_moved
            CHECK (upper(btrim(seen)) <> upper(btrim(means)));
    END IF;
END $$;

-- The suggestion query groups on exactly this pair.
CREATE INDEX IF NOT EXISTS ix_ocr_correction_samples_pair
    ON public.ocr_correction_samples (upper(btrim(seen)), upper(btrim(means)));

COMMIT;

-- ---------------------------------------------------------------------------
-- WHAT THIS TABLE DOES NOT DO
--
--   * It does not create corrections. A sample is evidence; a correction is a
--     decision. Promotion is always a person pressing a button, having seen
--     the count and the outcome preview. A rule created automatically after N
--     sightings is a rule nobody chose - and 'T' -> 'TRUE', which looked
--     obviously right and would have marked hundreds of correct answers
--     wrong, is the standing reminder of why that matters.
--
--   * It records nothing when a teacher corrects an item that was ALREADY
--     corrected by hand. The value being replaced then came from a person,
--     not from the reader, and is not evidence about the recogniser.
--     `ocr_confidence IS NULL` is what marks such a row - override_answer
--     nulls it precisely because the reading no longer stands.
