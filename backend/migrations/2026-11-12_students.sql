--
--     Other Option -> create 1st name of Student
--       * Test Paper -> ID # Student
--       * ID Student # -> file of Test Exam
--       * Primary Key [ ] -> Additional Table
--
-- and Doc Rubrica's "Create List of Students per Section".
--
-- This is the prerequisite for item 7, "Batch upload of Exam". The blocker
-- recorded in MULTI-PAGE-UPLOAD-2026-10-23.md was "the system cannot know
-- whose paper is whose"; a student number written on the paper and used as the
-- image's file name is what answers it.
--
-- RUN THIS, THEN RESTART THE BACKEND. Models and routes that reference
-- students will 500 against a database without these tables.
--
--   docker compose exec -T db psql -U postgres -d learnlens < 2026-11-12_students.sql

BEGIN;

CREATE TABLE IF NOT EXISTS public.students (
    student_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- The teacher who owns this roster. CASCADE: a deleted account takes its
    -- own roster with it, the same as exams.created_by already does.
    created_by      integer NOT NULL
                    REFERENCES public.users(user_id) ON DELETE CASCADE,

    -- The ID the school uses and the teacher writes on the paper. TEXT, not a
    -- number: real student numbers carry hyphens and leading zeros
    -- ("2021-00123", "04512"), and an integer column would silently eat both.
    student_number  character varying(50)  NOT NULL,

    last_name       character varying(255) NOT NULL,
    first_name      character varying(255) NOT NULL,

    -- "Create List of Students per Section". Free text for the same reason
    -- exams.schedule is free text (RUBRICA-2026-11-04): her sections are
    -- written however her school writes them, and a text column cannot be
    -- wrong about a label she chooses herself.
    section         character varying(255),

    created_at      timestamp with time zone DEFAULT now() NOT NULL,
    updated_at      timestamp with time zone DEFAULT now(),

    CONSTRAINT students_student_number_not_blank
        CHECK (trim(student_number) <> '')
);

-- UNIQUE PER TEACHER, NOT GLOBALLY. Two teachers at the same school may hold
-- the same student, and a global unique would make the second one's roster
-- impossible to fill.
--
-- lower() for the same reason users got ux_users_lower_email on 2026-11-11:
-- "2021-A123" and "2021-a123" are one student, and finding that out from a
-- duplicate paper at grading time is finding out too late. trim() because a
-- number pasted from a spreadsheet arrives with a trailing space.
CREATE UNIQUE INDEX IF NOT EXISTS ux_students_owner_number
    ON public.students (created_by, lower(trim(student_number)));

-- The roster screen lists by section, then surname.
CREATE INDEX IF NOT EXISTS ix_students_owner_section
    ON public.students (created_by, section);

-- The link. NULLABLE and ON DELETE SET NULL, both deliberate.
--
-- NULLABLE: every paper that exists today has no student row, exactly as
-- last_name / first_name were added nullable on 2026-11-04 and deliberately
-- not backfilled. A paper can also be added by name alone and linked later.
--
-- SET NULL, NEVER CASCADE: removing a student from the roster must not delete
-- their graded papers. Those rows are the record of an exam that happened, and
-- paper_scores CASCADEs off test_papers - so a CASCADE here would erase a
-- student's marked answers because a teacher tidied a class list. The paper
-- keeps its own last_name / first_name, so it stays readable after unlinking.
ALTER TABLE public.test_papers
    ADD COLUMN IF NOT EXISTS student_id integer
    REFERENCES public.students(student_id) ON DELETE SET NULL;

-- One paper per student per exam. The same rule the 2026-11-09 duplicate guard
-- enforces on names, now enforceable exactly rather than by string comparison -
-- which is the whole point of having an ID.
--
-- A PARTIAL index: WHERE student_id IS NOT NULL, so the unlinked papers that
-- exist today (all of them) do not collide with each other on NULL.
CREATE UNIQUE INDEX IF NOT EXISTS ux_test_papers_exam_student
    ON public.test_papers (exam_id, student_id)
    WHERE student_id IS NOT NULL;

COMMIT;

